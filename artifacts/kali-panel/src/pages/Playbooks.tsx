import { useState, useEffect } from "react";
import {
  ListChecks, Plus, Play, ChevronDown, ChevronRight, Tag, Clock,
  RefreshCw, CheckCircle, XCircle, Loader2, Trash2, Zap, Skull,
} from "lucide-react";
import { PageHeader } from "@/components/Layout";
import { jsonRequest } from "@/lib/sse";

interface PlaybookStep { id: number; stepOrder: number; title: string; toolName: string; toolInput: string; expectedOutput?: string; continueOnError: boolean; }
interface Playbook { id: number; title: string; description: string; category: string; tags: string; isAutoGenerated: boolean; runCount: number; lastRunAt?: string; createdAt: string; steps?: PlaybookStep[]; }
interface PlaybookRun { id: number; playbookId: number; status: string; startedAt: string; completedAt?: string; resultSummary?: string; triggeredBy: string; }

const CATEGORIES = ["all", "recon", "exploit", "defense", "scan", "custom", "general"];
const CAT_COLOR: Record<string, string> = {
  recon: "#44eebb", exploit: "#ff4444", defense: "#44ff88",
  scan: "#aa44ff", custom: "#ffaa44", general: "#4488ff",
};

const NEON_CARD = { background: "rgba(8,0,18,0.95)", border: "1px solid rgba(180,0,255,0.12)", borderRadius: 16, boxShadow: "0 0 20px rgba(150,0,255,0.04)" };
const DARK = { background: "rgba(5,0,12,0.8)", border: "1px solid rgba(255,255,255,0.05)", borderRadius: 12 };
const inputStyle: React.CSSProperties = { background: "rgba(255,255,255,0.03)", border: "1px solid rgba(255,255,255,0.08)", borderRadius: 10, color: "rgba(255,255,255,0.8)", fontSize: 12, fontFamily: "monospace", padding: "8px 12px", outline: "none" };

const TOOLS = ["run_shell", "scan_url", "nvd_search", "cisa_kev", "github_search", "exploit_db_search", "fetch_url", "scan_target", "memory_save", "memory_search"];

export default function Playbooks() {
  const [playbooks, setPlaybooks] = useState<Playbook[]>([]);
  const [runs, setRuns] = useState<PlaybookRun[]>([]);
  const [loading, setLoading] = useState(true);
  const [expandedId, setExpandedId] = useState<number | null>(null);
  const [expandedSteps, setExpandedSteps] = useState<Record<number, PlaybookStep[]>>({});
  const [filter, setFilter] = useState("all");
  const [runningId, setRunningId] = useState<number | null>(null);
  const [showCreate, setShowCreate] = useState(false);
  const [form, setForm] = useState({ title: "", description: "", category: "general", tags: "" });
  const [steps, setSteps] = useState<Array<{ title: string; toolName: string; toolInput: string }>>([{ title: "", toolName: "run_shell", toolInput: "" }]);

  async function load() {
    setLoading(true);
    try {
      const [pbs, rns] = await Promise.all([jsonRequest<Playbook[]>("/playbooks"), jsonRequest<PlaybookRun[]>("/playbooks/runs").catch(() => [])]);
      setPlaybooks(pbs);
      setRuns(Array.isArray(rns) ? rns : []);
    } catch { } finally { setLoading(false); }
  }

  useEffect(() => { void load(); }, []);

  async function expandPlaybook(id: number) {
    if (expandedId === id) { setExpandedId(null); return; }
    setExpandedId(id);
    if (!expandedSteps[id]) {
      const pb = await jsonRequest<Playbook & { steps: PlaybookStep[] }>(`/playbooks/${id}`);
      setExpandedSteps((p) => ({ ...p, [id]: pb.steps ?? [] }));
    }
  }

  async function runPlaybook(id: number) {
    setRunningId(id);
    try { await jsonRequest(`/playbooks/${id}/run`, { method: "POST" }); await load(); }
    catch { } finally { setRunningId(null); }
  }

  async function deletePlaybook(id: number) {
    if (!confirm("حذف هذا الـ Playbook؟")) return;
    await jsonRequest(`/playbooks/${id}`, { method: "DELETE" });
    setPlaybooks((p) => p.filter((x) => x.id !== id));
  }

  async function createPlaybook() {
    if (!form.title) return;
    await jsonRequest("/playbooks", { method: "POST", body: JSON.stringify({ ...form, steps: steps.filter((s) => s.title && s.toolName) }) });
    setShowCreate(false);
    setForm({ title: "", description: "", category: "general", tags: "" });
    setSteps([{ title: "", toolName: "run_shell", toolInput: "" }]);
    await load();
  }

  const filtered = filter === "all" ? playbooks : playbooks.filter((p) => p.category === filter);

  return (
    <div className="min-h-screen p-5 space-y-5" style={{ background: "linear-gradient(180deg,#060010 0%,#03000a 100%)" }} dir="rtl">
      <PageHeader title="⚡ Playbooks" subtitle="خطط تنفيذ جاهزة — تعلم ذاتي وتنفيذ متسلسل للمهام الأمنية" icon={ListChecks} danger
        actions={
          <div className="flex items-center gap-2">
            <button onClick={load} className="p-2 rounded-xl transition-all" style={{ background: "rgba(255,255,255,0.02)", border: "1px solid rgba(255,255,255,0.06)", color: "rgba(255,255,255,0.35)" }}>
              <RefreshCw className="w-4 h-4" />
            </button>
            <button onClick={() => setShowCreate(true)}
              className="flex items-center gap-1.5 font-black text-[11px] font-mono px-3 py-2 rounded-xl transition-all"
              style={{ background: "rgba(255,30,30,0.1)", border: "1px solid rgba(255,30,30,0.3)", color: "#ff5555" }}>
              <Plus className="w-3.5 h-3.5" />إنشاء Playbook
            </button>
          </div>
        }
      />

      {/* ── Stats ── */}
      <div className="grid grid-cols-4 gap-3">
        {[
          { label: "إجمالي", value: playbooks.length, color: "#4488ff" },
          { label: "AI مُولّدة", value: playbooks.filter((p) => p.isAutoGenerated).length, color: "#aa44ff" },
          { label: "إجمالي التشغيل", value: playbooks.reduce((a, b) => a + b.runCount, 0), color: "#44ff88" },
          { label: "تشغيلات ناجحة", value: runs.filter((r) => r.status === "completed").length, color: "#ffaa44" },
        ].map(({ label, value, color }) => (
          <div key={label} className="rounded-xl p-4 text-center" style={{ ...NEON_CARD, borderColor: `${color}20` }}>
            <div className="text-2xl font-black font-mono" style={{ color, textShadow: `0 0 12px ${color}55` }}>{value}</div>
            <div className="text-[9px] font-mono mt-1" style={{ color: "rgba(255,255,255,0.3)" }}>{label}</div>
          </div>
        ))}
      </div>

      {/* ── Category Filter ── */}
      <div className="flex gap-1.5 flex-wrap">
        {CATEGORIES.map((cat) => {
          const color = cat === "all" ? "#ff5555" : (CAT_COLOR[cat] ?? "#888");
          return (
            <button key={cat} onClick={() => setFilter(cat)}
              className="text-[10px] font-black font-mono px-3 py-1.5 rounded-xl transition-all"
              style={filter === cat
                ? { background: `${color}14`, border: `1px solid ${color}38`, color }
                : { background: "rgba(255,255,255,0.02)", border: "1px solid rgba(255,255,255,0.05)", color: "rgba(255,255,255,0.35)" }}>
              {cat === "all" ? "الكل" : cat}
            </button>
          );
        })}
      </div>

      {/* ── Create Form ── */}
      {showCreate && (
        <div className="rounded-2xl p-5 space-y-4" style={{ ...NEON_CARD, border: "1px solid rgba(255,30,30,0.22)" }}>
          <h3 className="font-black text-sm flex items-center gap-2" style={{ color: "#ff5555" }}>
            <Plus className="w-4 h-4" />إنشاء Playbook جديد
          </h3>
          <div className="grid grid-cols-2 gap-3">
            <div>
              <label className="text-[9px] font-black font-mono mb-1 block" style={{ color: "rgba(255,255,255,0.35)" }}>العنوان *</label>
              <input placeholder="مثال: Recon كامل" value={form.title}
                onChange={(e) => setForm((f) => ({ ...f, title: e.target.value }))}
                style={{ ...inputStyle, width: "100%" }} />
            </div>
            <div>
              <label className="text-[9px] font-black font-mono mb-1 block" style={{ color: "rgba(255,255,255,0.35)" }}>الفئة</label>
              <select value={form.category} onChange={(e) => setForm((f) => ({ ...f, category: e.target.value }))}
                style={{ ...inputStyle, width: "100%" } as React.CSSProperties}>
                {CATEGORIES.filter((c) => c !== "all").map((c) => <option key={c} value={c}>{c}</option>)}
              </select>
            </div>
          </div>
          <div>
            <label className="text-[9px] font-black font-mono mb-1 block" style={{ color: "rgba(255,255,255,0.35)" }}>الوصف</label>
            <textarea value={form.description} onChange={(e) => setForm((f) => ({ ...f, description: e.target.value }))}
              rows={2} style={{ ...inputStyle, width: "100%", resize: "none" } as React.CSSProperties} />
          </div>
          <div>
            <div className="flex items-center justify-between mb-2">
              <label className="text-[9px] font-black font-mono" style={{ color: "rgba(255,255,255,0.35)" }}>الخطوات</label>
              <button onClick={() => setSteps((s) => [...s, { title: "", toolName: "run_shell", toolInput: "" }])}
                className="text-[10px] font-black font-mono flex items-center gap-1 transition-all"
                style={{ color: "#44ff88" }}>
                <Plus className="w-3 h-3" />خطوة
              </button>
            </div>
            <div className="space-y-2">
              {steps.map((step, i) => (
                <div key={i} className="grid grid-cols-3 gap-2 rounded-xl p-2" style={DARK}>
                  <input placeholder="عنوان الخطوة" value={step.title}
                    onChange={(e) => setSteps((s) => s.map((x, j) => j === i ? { ...x, title: e.target.value } : x))}
                    style={{ ...inputStyle, fontSize: 11 }} />
                  <select value={step.toolName}
                    onChange={(e) => setSteps((s) => s.map((x, j) => j === i ? { ...x, toolName: e.target.value } : x))}
                    style={{ ...inputStyle, fontSize: 11 } as React.CSSProperties}>
                    {TOOLS.map((t) => <option key={t} value={t}>{t}</option>)}
                  </select>
                  <input placeholder='{"command":"ls"}' value={step.toolInput}
                    onChange={(e) => setSteps((s) => s.map((x, j) => j === i ? { ...x, toolInput: e.target.value } : x))}
                    style={{ ...inputStyle, fontSize: 11 }} />
                </div>
              ))}
            </div>
          </div>
          <div className="flex gap-2 justify-end">
            <button onClick={() => setShowCreate(false)}
              className="text-[11px] font-mono px-3 py-1.5 rounded-xl transition-all"
              style={{ background: "rgba(255,255,255,0.03)", border: "1px solid rgba(255,255,255,0.07)", color: "rgba(255,255,255,0.4)" }}>
              إلغاء
            </button>
            <button onClick={() => void createPlaybook()}
              className="text-[11px] font-black font-mono px-4 py-1.5 rounded-xl transition-all"
              style={{ background: "rgba(255,30,30,0.12)", border: "1px solid rgba(255,30,30,0.32)", color: "#ff5555" }}>
              حفظ Playbook
            </button>
          </div>
        </div>
      )}

      {/* ── Playbooks List ── */}
      {loading ? (
        <div className="flex items-center justify-center py-16">
          <Loader2 className="w-8 h-8 animate-spin" style={{ color: "#ff5555" }} />
        </div>
      ) : filtered.length === 0 ? (
        <div className="rounded-2xl p-12 text-center space-y-3" style={NEON_CARD}>
          <Skull className="w-12 h-12 mx-auto" style={{ color: "rgba(255,255,255,0.06)" }} />
          <p className="font-mono text-sm" style={{ color: "rgba(255,255,255,0.2)" }}>لا توجد Playbooks — أنشئ الأول الآن</p>
        </div>
      ) : (
        <div className="space-y-2">
          {filtered.map((pb) => {
            const catColor = CAT_COLOR[pb.category] ?? "#888";
            return (
              <div key={pb.id} className="rounded-2xl overflow-hidden transition-all" style={NEON_CARD}>
                <div className="p-4 flex items-center gap-3 cursor-pointer"
                  style={{ borderBottom: expandedId === pb.id ? "1px solid rgba(255,255,255,0.05)" : "none" }}
                  onClick={() => void expandPlaybook(pb.id)}>
                  <div className="flex-1 min-w-0">
                    <div className="flex items-center gap-2 mb-1 flex-wrap">
                      <span className="font-black text-sm" style={{ color: "rgba(255,255,255,0.8)" }}>{pb.title}</span>
                      <span className="text-[9px] font-black font-mono px-1.5 py-0.5 rounded"
                        style={{ color: catColor, background: `${catColor}14`, border: `1px solid ${catColor}30` }}>
                        {pb.category}
                      </span>
                      {pb.isAutoGenerated && (
                        <span className="text-[9px] font-black font-mono px-1.5 py-0.5 rounded flex items-center gap-1"
                          style={{ color: "#aa44ff", background: "rgba(170,0,255,0.1)", border: "1px solid rgba(170,0,255,0.28)" }}>
                          <Zap className="w-2.5 h-2.5" />AI
                        </span>
                      )}
                    </div>
                    <p className="text-[10px] font-mono truncate" style={{ color: "rgba(255,255,255,0.35)" }}>{pb.description || "بدون وصف"}</p>
                    <div className="flex items-center gap-3 mt-1 text-[9px] font-mono" style={{ color: "rgba(255,255,255,0.25)" }}>
                      {pb.tags && <span className="flex items-center gap-1"><Tag className="w-2.5 h-2.5" />{pb.tags}</span>}
                      <span className="flex items-center gap-1"><Play className="w-2.5 h-2.5" />{pb.runCount} تشغيل</span>
                      {pb.lastRunAt && <span className="flex items-center gap-1"><Clock className="w-2.5 h-2.5" />{new Date(pb.lastRunAt).toLocaleDateString("ar-EG")}</span>}
                    </div>
                  </div>
                  <div className="flex items-center gap-2">
                    <button onClick={(e) => { e.stopPropagation(); void runPlaybook(pb.id); }}
                      disabled={runningId === pb.id}
                      className="flex items-center gap-1 text-[10px] font-black font-mono px-2.5 py-1.5 rounded-xl transition-all disabled:opacity-50"
                      style={{ background: "rgba(0,200,100,0.08)", border: "1px solid rgba(0,200,100,0.22)", color: "#44ff88" }}>
                      {runningId === pb.id ? <Loader2 className="w-3 h-3 animate-spin" /> : <Play className="w-3 h-3" />}تشغيل
                    </button>
                    <button onClick={(e) => { e.stopPropagation(); void deletePlaybook(pb.id); }}
                      className="p-1.5 rounded-xl transition-all"
                      style={{ color: "rgba(255,255,255,0.2)" }}
                      onMouseEnter={e => { (e.currentTarget as HTMLElement).style.color = "#ff5555"; }}
                      onMouseLeave={e => { (e.currentTarget as HTMLElement).style.color = "rgba(255,255,255,0.2)"; }}>
                      <Trash2 className="w-3.5 h-3.5" />
                    </button>
                    {expandedId === pb.id
                      ? <ChevronDown className="w-4 h-4" style={{ color: "rgba(255,255,255,0.3)" }} />
                      : <ChevronRight className="w-4 h-4" style={{ color: "rgba(255,255,255,0.3)" }} />}
                  </div>
                </div>

                {expandedId === pb.id && (
                  <div className="p-4 space-y-2" style={{ background: "rgba(0,0,0,0.2)" }}>
                    <h4 className="text-[9px] font-black font-mono uppercase mb-3" style={{ color: "rgba(255,255,255,0.3)" }}>الخطوات</h4>
                    {(expandedSteps[pb.id] ?? []).length === 0 ? (
                      <p className="text-[10px] font-mono" style={{ color: "rgba(255,255,255,0.2)" }}>لا توجد خطوات محددة</p>
                    ) : (expandedSteps[pb.id] ?? []).map((step, idx) => (
                      <div key={step.id} className="flex items-start gap-3 rounded-xl p-3" style={DARK}>
                        <span className="text-[10px] font-black font-mono w-5 shrink-0" style={{ color: "rgba(255,255,255,0.25)" }}>{idx + 1}</span>
                        <div className="flex-1 min-w-0">
                          <div className="flex items-center gap-2 mb-1">
                            <span className="text-[11px] font-black" style={{ color: "rgba(255,255,255,0.7)" }}>{step.title}</span>
                            <span className="text-[9px] font-black font-mono px-1.5 py-0.5 rounded"
                              style={{ background: "rgba(255,170,0,0.1)", border: "1px solid rgba(255,170,0,0.22)", color: "#ffaa44" }}>
                              {step.toolName}
                            </span>
                          </div>
                          {step.toolInput && (
                            <code className="text-[9px] font-mono" style={{ color: "rgba(255,255,255,0.3)" }}>
                              {step.toolInput.slice(0, 80)}
                            </code>
                          )}
                        </div>
                      </div>
                    ))}
                  </div>
                )}
              </div>
            );
          })}
        </div>
      )}

      {/* ── Recent Runs ── */}
      {runs.length > 0 && (
        <div className="rounded-2xl p-4 space-y-3" style={NEON_CARD}>
          <h3 className="font-black text-sm flex items-center gap-2" style={{ color: "#ffaa44" }}>
            <Clock className="w-4 h-4" />التشغيلات الأخيرة
          </h3>
          <div className="space-y-2">
            {runs.slice(0, 10).map((run) => (
              <div key={run.id} className="flex items-center gap-3 p-2 rounded-xl" style={DARK}>
                {run.status === "completed"
                  ? <CheckCircle className="w-4 h-4 shrink-0" style={{ color: "#44ff88" }} />
                  : run.status === "failed"
                  ? <XCircle className="w-4 h-4 shrink-0" style={{ color: "#ff4444" }} />
                  : <Loader2 className="w-4 h-4 animate-spin shrink-0" style={{ color: "#ffaa44" }} />}
                <div className="flex-1 min-w-0">
                  <div className="flex items-center gap-2">
                    <span className="text-[10px] font-black font-mono" style={{ color: "rgba(255,255,255,0.6)" }}>
                      Playbook #{run.playbookId}
                    </span>
                    <span className="text-[9px] font-black font-mono px-1.5 py-0.5 rounded"
                      style={{
                        color: run.status === "completed" ? "#44ff88" : run.status === "failed" ? "#ff4444" : "#ffaa44",
                        background: run.status === "completed" ? "rgba(0,200,100,0.08)" : run.status === "failed" ? "rgba(255,30,30,0.08)" : "rgba(255,170,0,0.08)",
                      }}>
                      {run.status}
                    </span>
                  </div>
                  {run.resultSummary && (
                    <p className="text-[9px] font-mono truncate" style={{ color: "rgba(255,255,255,0.3)" }}>{run.resultSummary}</p>
                  )}
                </div>
                <div className="text-[9px] font-mono" style={{ color: "rgba(255,255,255,0.2)" }}>
                  {new Date(run.startedAt).toLocaleString("ar-EG")}
                </div>
              </div>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}
