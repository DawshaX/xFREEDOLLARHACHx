#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# NOVA — turn a fresh Linux box into a working node, in one command.
# ─────────────────────────────────────────────────────────────────────────────
# Written for the machines that cost nothing and need no card:
#
#   • GitHub Codespaces   → 120 core-hours/month free (a real Ubuntu box, root)
#   • Fly.io Sprite       → real Linux, ~300ms wake, bills only while awake
#   • Oracle Always Free  → 4 ARM cores / 24 GB, free forever (card to verify)
#   • any VPS / your own  → wherever you can run bash
#
# What this does, and why each step is here rather than in a README:
#   1. pnpm (the repo is a workspace — npm cannot resolve `workspace:*`)
#   2. dependencies, then BOTH builds (engine + panel served by the engine)
#   3. the real tools (nuclei, httpx, katana, subfinder) vendored as static
#      binaries — no root, no apt, and `--ignore-scripts` installs never break
#   4. a token, generated once and kept, because the gate needs one the moment
#      the engine is reachable from the internet
#
# It is idempotent: run it again after a git pull and it only does what changed.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
say() { printf '\n\033[1;36m▸ %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m  ! %s\033[0m\n' "$*"; }

say "1/5 node"
if ! command -v node >/dev/null 2>&1; then
  echo "node is not installed. Codespaces/Sprites images ship node 22; if yours does not:"
  echo "  curl -fsSL https://deb.nodesource.com/setup_22.x | sudo -E bash - && sudo apt-get install -y nodejs"
  exit 1
fi
NODE_MAJOR="$(node -p 'process.versions.node.split(".")[0]')"
if [ "$NODE_MAJOR" -lt 22 ]; then
  warn "node $(node -v) is older than 22 — the engine uses built-in fetch and AbortSignal.timeout; expect failures"
fi
echo "  node $(node -v)"

say "2/5 pnpm"
if command -v pnpm >/dev/null 2>&1; then
  echo "  pnpm $(pnpm -v)"
else
  corepack enable >/dev/null 2>&1 || true
  corepack prepare pnpm@10.34.9 --activate >/dev/null 2>&1 || npm install -g pnpm@10.34.9
  echo "  pnpm $(pnpm -v) (installed now)"
fi

say "3/5 dependencies"
# --ignore-scripts: postinstall scripts are what make a workspace install fail on
# a locked-down host, and nothing here needs one (esbuild ships prebuilt).
pnpm install --no-frozen-lockfile --ignore-scripts

say "4/5 builds (engine + panel in one process)"
pnpm --filter @workspace/api-server run build
BASE_PATH=/ pnpm --filter @workspace/kali-panel run build

say "5/5 real tools (static binaries, no root)"
# GitHub's API rate-limits anonymous callers to 60 requests/hour per IP, and a
# fresh cloud IP often shares that budget with tenants that already spent it.
# If the box already has `gh` logged in, borrow its token so the download does
# not depend on luck.
if [ -z "${GITHUB_TOKEN:-}" ] && command -v gh >/dev/null 2>&1; then
  if GH_TOKEN_FOUND="$(gh auth token 2>/dev/null)" && [ -n "$GH_TOKEN_FOUND" ]; then
    export GITHUB_TOKEN="$GH_TOKEN_FOUND"
    echo "  using the gh CLI's token for release downloads"
  fi
fi
# Never fatal: a node without nuclei is still a working node that says so.
node scripts/fetch-toolchain.mjs --into vendor/bin || warn "toolchain fetch failed — the engine will report the tools as missing, not pretend"
node scripts/check-toolchain.mjs --dir vendor/bin || true

# ── the token ────────────────────────────────────────────────────────────────
if [ ! -f .env.local ]; then
  TOKEN="$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')"
  cat > .env.local <<EOF
# generated by scripts/nova-machine-setup.sh — never commit this file
NODE_ENV=production
PORT=8080
HOST=0.0.0.0
NOVA_EXEC_TOKEN=$TOKEN
NOVA_TOOL_DIR=$ROOT/vendor/bin
EOF
  say "token created in .env.local"
else
  echo "  .env.local already exists — token left alone"
fi

cat <<'EOF'

────────────────────────────────────────────────────────────────────────────
Done. Start it:

    ./scripts/nova-serve.sh

Then open the engine's own panel on port 8080 — and in the Pages build open
«محطة نوفا» and paste the public URL + the token from .env.local, so the fleet
page talks to THIS machine instead of the browser's built-in stub.

The public URL depends on the host:
  Codespaces → Ports tab → port 8080 → Visibility: Public → copy the https URL
  Sprite     → https://<sprite-name>.sprites.app  (it wakes on the first request)
  Oracle/VPS → your domain or http://<ip>:8080 (open the port in the firewall)
────────────────────────────────────────────────────────────────────────────
EOF
