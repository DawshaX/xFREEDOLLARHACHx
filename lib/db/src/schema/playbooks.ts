import { pgTable, serial, text, timestamp, integer, boolean } from "drizzle-orm/pg-core";

export const playbooks = pgTable("playbooks", {
  id: serial("id").primaryKey(),
  title: text("title").notNull(),
  description: text("description").notNull().default(""),
  category: text("category").notNull().default("general"),
  tags: text("tags").notNull().default(""),
  isAutoGenerated: boolean("is_auto_generated").notNull().default(false),
  sourceSessionId: integer("source_session_id"),
  runCount: integer("run_count").notNull().default(0),
  lastRunAt: timestamp("last_run_at", { withTimezone: true }),
  createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).defaultNow().notNull(),
});

export const playbookSteps = pgTable("playbook_steps", {
  id: serial("id").primaryKey(),
  playbookId: integer("playbook_id")
    .notNull()
    .references(() => playbooks.id, { onDelete: "cascade" }),
  stepOrder: integer("step_order").notNull().default(0),
  title: text("title").notNull(),
  toolName: text("tool_name").notNull(),
  toolInput: text("tool_input").notNull().default("{}"),
  expectedOutput: text("expected_output").default(""),
  continueOnError: boolean("continue_on_error").notNull().default(false),
  createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
});

export const playbookRuns = pgTable("playbook_runs", {
  id: serial("id").primaryKey(),
  playbookId: integer("playbook_id")
    .notNull()
    .references(() => playbooks.id, { onDelete: "cascade" }),
  status: text("status").notNull().default("running"),
  startedAt: timestamp("started_at", { withTimezone: true }).defaultNow().notNull(),
  completedAt: timestamp("completed_at", { withTimezone: true }),
  resultSummary: text("result_summary").default(""),
  triggeredBy: text("triggered_by").notNull().default("user"),
});

export type Playbook = typeof playbooks.$inferSelect;
export type InsertPlaybook = typeof playbooks.$inferInsert;
export type PlaybookStep = typeof playbookSteps.$inferSelect;
export type PlaybookRun = typeof playbookRuns.$inferSelect;
